    private ActivityLiveBinding binding;
    private final Handler handler = new Handler(Looper.getMainLooper());
    private final Random random = new Random();
    private final List<Comment> comments = new ArrayList<>();

    private ProcessCameraProvider cameraProvider;
    private boolean cameraBound;
    private boolean cameraRequestInFlight;

    private boolean permissionRequested;
    private boolean permissionRequestInFlight;

    private boolean live;
    private boolean simulationRunning;
    private boolean endDialogVisible;
    private String liveTitle = "";

    private int viewerCount;
    private int lastUsernameIndex = -1;
    private long elapsedMs;
    private long lastResumeRealtime;

    private ObjectAnimator liveDotAnimator;

    private final ActivityResultLauncher<String> permissionLauncher =
            registerForActivityResult(new ActivityResultContracts.RequestPermission(), granted -> {
                permissionRequestInFlight = false;
                permissionRequested = true;
                if (binding == null) return;
                if (granted) {
                    binding.permissionPanel.setVisibility(View.GONE);
                    ensureCamera();
                } else {
                    showPermissionPanel();
                }
            });

    // ---------------------------------------------------------------------
    // Lifecycle
    // ---------------------------------------------------------------------

    @Override
    protected void onCreate(@Nullable Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        WindowCompat.setDecorFitsSystemWindows(getWindow(), false);
        binding = ActivityLiveBinding.inflate(getLayoutInflater());
        setContentView(binding.getRoot());

        if (savedInstanceState != null) {
            restoreState(savedInstanceState);
        }

        bindListeners();
        applyWindowInsets();

        if (live) {
            // Rotation / process death while streaming: reopen straight into
            // the stream so the camera never flashes the setup sheet.
            showStreamUi(liveTitle);
            updateViewerCount();
            binding.tvLiveTimer.setText(formatDuration(elapsedMs));
            restoreComments(savedInstanceState);
        }

        if (hasCameraPermission()) {
            ensureCamera();
        } else if (savedInstanceState == null) {
            requestCameraPermission();
        } else if (permissionRequested) {
            showPermissionPanel();
        }
    }

    @Override
    protected void onResume() {
        super.onResume();
        if (binding == null) return;
        // Returning from the system Settings screen may have granted access.
        if (hasCameraPermission()) {
            binding.permissionPanel.setVisibility(View.GONE);
            ensureCamera();
        } else if (permissionRequested && !permissionRequestInFlight) {
            showPermissionPanel();
        }
    }

    @Override
    protected void onStart() {
        super.onStart();
        if (live) {
            startSimulation();
        }
    }

    @Override
    protected void onStop() {
        // Viewers and comments are paused while the app is not visible; the
        // camera itself is stopped by the CameraX lifecycle binding.
        stopSimulation();
        super.onStop();
    }

    @Override
    protected void onDestroy() {
        stopSimulation();
        handler.removeCallbacksAndMessages(null);
        stopLiveDotPulse();
        releaseCamera();
        super.onDestroy();
    }

    @Override
    protected void onSaveInstanceState(@NonNull Bundle outState) {
        super.onSaveInstanceState(outState);
        outState.putBoolean(STATE_LIVE, live);
        outState.putInt(STATE_VIEWERS, viewerCount);
        outState.putString(STATE_TITLE, liveTitle);
        outState.putLong(STATE_ELAPSED, currentElapsedMs());
        outState.putBoolean(STATE_PERMISSION_REQUESTED, permissionRequested);

        ArrayList<String> users = new ArrayList<>(comments.size());
        ArrayList<String> messages = new ArrayList<>(comments.size());
        for (Comment comment : comments) {
            users.add(comment.username);
            messages.add(comment.message);
        }
        outState.putStringArrayList(STATE_COMMENT_USERS, users);
        outState.putStringArrayList(STATE_COMMENT_MESSAGES, messages);
    }

    private void restoreState(@NonNull Bundle state) {
        live = state.getBoolean(STATE_LIVE, false);
        viewerCount = state.getInt(STATE_VIEWERS, 0);
        liveTitle = state.getString(STATE_TITLE, "");
        if (liveTitle == null) liveTitle = "";
        elapsedMs = state.getLong(STATE_ELAPSED, 0L);
        permissionRequested = state.getBoolean(STATE_PERMISSION_REQUESTED, false);
    }

    private void bindListeners() {
        binding.btnCloseSetup.setOnClickListener(v -> finish());
        binding.btnStartLive.setOnClickListener(v -> onStartLiveClicked());
        binding.btnEndLive.setOnClickListener(v -> confirmEndLive());
        binding.btnCameraError.setOnClickListener(v -> {
            hideCameraError();
            ensureCamera();
        });
        binding.btnPermissionNotNow.setOnClickListener(v -> finish());
        binding.btnGrantCamera.setOnClickListener(v -> {
            if (isPermissionPermanentlyDenied()) {
                openAppSettings();
            } else {
                requestCameraPermission();
            }
        });
        binding.etLiveTopic.setOnEditorActionListener((v, actionId, event) -> {
            if (actionId == android.view.inputmethod.EditorInfo.IME_ACTION_DONE) {
                onStartLiveClicked();
                return true;
            }
            return false;
        });

        getOnBackPressedDispatcher().addCallback(this, new OnBackPressedCallback(true) {
            @Override
            public void handleOnBackPressed() {
                // Never drop the viewer/camera without confirmation while live.
                if (live) {
                    confirmEndLive();
                } else {
                    finish();
                }
            }
        });
    }

    // ---------------------------------------------------------------------
    // Setup -> stream
    // ---------------------------------------------------------------------

    private void onStartLiveClicked() {
        if (!hasCameraPermission()) {
            if (isPermissionPermanentlyDenied()) {
                showPermissionPanel();
            } else {
                requestCameraPermission();
            }
            return;
        }
        startLive();
    }

    private void startLive() {
        KeyboardUtils.hideKeyboard(this);
        binding.etLiveTopic.clearFocus();

        liveTitle = binding.etLiveTopic.getText().toString().trim();
        elapsedMs = 0L;
        lastResumeRealtime = 0L;
        viewerCount = 4 + random.nextInt(5);
        comments.clear();
        binding.commentsContainer.removeAllViews();
        binding.tvLiveTimer.setText(formatDuration(0L));

        showStreamUi(liveTitle);
        updateViewerCount();
        startSimulation();
    }

    /** Switches the chrome from setup to stream without touching the camera. */
    private void showStreamUi(@Nullable String title) {
        live = true;
        binding.setupPanel.setVisibility(View.GONE);
        binding.streamPanel.setVisibility(View.VISIBLE);
        if (cameraBound) {
            hideCameraError();
        }

        String safeTitle = title == null ? "" : title.trim();
        if (safeTitle.isEmpty()) {
            binding.tvLiveTitle.setVisibility(View.GONE);
        } else {
            binding.tvLiveTitle.setVisibility(View.VISIBLE);
            binding.tvLiveTitle.setText(safeTitle);
        }
    }

    private void confirmEndLive() {
        if (endDialogVisible) return;
        AlertDialog dialog = new AlertDialog.Builder(this)
                .setTitle(R.string.live_end_confirm_title)
                .setMessage(R.string.live_end_confirm_message)
                .setNegativeButton(R.string.live_cancel, (d, which) -> endDialogVisible = false)
                .setPositiveButton(R.string.live_end_confirm_action, (d, which) -> {
                    endDialogVisible = false;
                    endLive();
                })
                .create();
        dialog.setOnCancelListener(d -> endDialogVisible = false);
        dialog.setOnDismissListener(d -> endDialogVisible = false);
        dialog.show();
        endDialogVisible = true;
        dialog.getButton(AlertDialog.BUTTON_POSITIVE)
                .setTextColor(ContextCompat.getColor(this, R.color.color_destructive));
        dialog.getButton(AlertDialog.BUTTON_NEGATIVE)
                .setTextColor(ContextCompat.getColor(this, R.color.color_text_secondary));
    }

    private void endLive() {
        if (!live) {
            finish();
            return;
        }
        live = false;
        stopSimulation();
        releaseCamera();
        ToastUtil.showPill(this, getString(R.string.live_ended));
        finish();
    }

    // ---------------------------------------------------------------------
    // Simulated audience
    // ---------------------------------------------------------------------

    private void startSimulation() {
        if (!live || simulationRunning) return;
        simulationRunning = true;
        lastResumeRealtime = SystemClock.elapsedRealtime();
        getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
        startLiveDotPulse();
        handler.postDelayed(viewerTick, VIEWER_TICK_MS);
        handler.postDelayed(timerTick, TIMER_TICK_MS);
        handler.postDelayed(commentTick, FIRST_COMMENT_DELAY_MS);
    }

    private void stopSimulation() {
        if (!simulationRunning) return;
        simulationRunning = false;
        handler.removeCallbacks(viewerTick);
        handler.removeCallbacks(timerTick);
        handler.removeCallbacks(commentTick);
        if (lastResumeRealtime != 0L) {
            elapsedMs += Math.max(0L, SystemClock.elapsedRealtime() - lastResumeRealtime);
            lastResumeRealtime = 0L;
        }
        getWindow().clearFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
        stopLiveDotPulse();
    }

    private final Runnable viewerTick = new Runnable() {
        @Override
        public void run() {
            if (!live || !simulationRunning) return;
            int delta;
            if (random.nextInt(100) < 10 && viewerCount > 4) {
                // A few people always leave; the trend still climbs.
                delta = -(1 + random.nextInt(2));
            } else {
                delta = 1 + random.nextInt(4);
            }
            viewerCount = Math.max(1, Math.min(MAX_VIEWERS, viewerCount + delta));
            updateViewerCount();
            pulseViewerCount();
            handler.postDelayed(this, VIEWER_TICK_MS);
        }
    };

    private final Runnable timerTick = new Runnable() {
        @Override
        public void run() {
            if (!live || !simulationRunning) return;
            binding.tvLiveTimer.setText(formatDuration(currentElapsedMs()));
            handler.postDelayed(this, TIMER_TICK_MS);
        }
    };

    private final Runnable commentTick = new Runnable() {
        @Override
        public void run() {
            if (!live || !simulationRunning) return;
            addComment(COMMENT_USERS[nextUsernameIndex()],
                    COMMENT_MESSAGES[random.nextInt(COMMENT_MESSAGES.length)], true);
            handler.postDelayed(this, 2200L + random.nextInt(2200));
        }
    };

    private int nextUsernameIndex() {
        int index = random.nextInt(COMMENT_USERS.length);
        if (index == lastUsernameIndex && COMMENT_USERS.length > 1) {
            index = (index + 1) % COMMENT_USERS.length;
        }
        lastUsernameIndex = index;
        return index;
    }

    private void addComment(String username, String message, boolean animate) {
        if (binding == null) return;

        View row = LayoutInflater.from(this)
                .inflate(R.layout.item_live_comment, binding.commentsContainer, false);
        TextView text = row.findViewById(R.id.commentText);

        SpannableString content = new SpannableString(username + "  " + message);
        content.setSpan(new StyleSpan(Typeface.BOLD), 0, username.length(),
                Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
        text.setText(content);

        LinearLayout.LayoutParams params = new LinearLayout.LayoutParams(
                ViewGroup.LayoutParams.WRAP_CONTENT, ViewGroup.LayoutParams.WRAP_CONTENT);
        params.topMargin = dp(6);
        row.setLayoutParams(params);
        binding.commentsContainer.addView(row);

        while (binding.commentsContainer.getChildCount() > MAX_COMMENTS) {
            binding.commentsContainer.removeViewAt(0);
        }
        comments.add(new Comment(username, message));
        while (comments.size() > MAX_COMMENTS) {
            comments.remove(0);
        }

        if (animate) {
            row.setAlpha(0f);
            row.setTranslationY(dp(10));
            row.animate().alpha(1f).translationY(0f).setDuration(200L).start();
        }
    }

    private void restoreComments(@Nullable Bundle state) {
        if (state == null) return;
        ArrayList<String> users = state.getStringArrayList(STATE_COMMENT_USERS);
        ArrayList<String> messages = state.getStringArrayList(STATE_COMMENT_MESSAGES);
        if (users == null || messages == null) return;
        int count = Math.min(users.size(), messages.size());
        for (int i = 0; i < count; i++) {
            addComment(users.get(i), messages.get(i), false);
        }
    }

    private void updateViewerCount() {
        binding.tvViewerCount.setText(
                getResources().getQuantityString(R.plurals.live_viewers, viewerCount, viewerCount));
    }

    private void pulseViewerCount() {
        binding.tvViewerCount.animate()
                .scaleX(1.08f).scaleY(1.08f).setDuration(120L)
                .withEndAction(() -> {
                    if (binding == null) return;
                    binding.tvViewerCount.animate()
                            .scaleX(1f).scaleY(1f).setDuration(120L).start();
                })
                .start();
    }

    private long currentElapsedMs() {
        if (!simulationRunning || lastResumeRealtime == 0L) return elapsedMs;
        return elapsedMs + Math.max(0L, SystemClock.elapsedRealtime() - lastResumeRealtime);
    }

    private String formatDuration(long millis) {
        long totalSeconds = millis / 1000L;
        long hours = totalSeconds / 3600L;
        long minutes = (totalSeconds % 3600L) / 60L;
        long seconds = totalSeconds % 60L;
        if (hours > 0L) {
            return String.format(Locale.US, "%d:%02d:%02d", hours, minutes, seconds);
        }
        return String.format(Locale.US, "%02d:%02d", minutes, seconds);
    }

    private void startLiveDotPulse() {
        if (binding == null || liveDotAnimator != null) return;
        liveDotAnimator = ObjectAnimator.ofFloat(binding.liveDot, View.ALPHA, 1f, 0.25f);
        liveDotAnimator.setDuration(750L);
        liveDotAnimator.setRepeatMode(ValueAnimator.REVERSE);
        liveDotAnimator.setRepeatCount(ValueAnimator.INFINITE);
        liveDotAnimator.start();
    }

    private void stopLiveDotPulse() {
        if (liveDotAnimator != null) {
            liveDotAnimator.cancel();
            liveDotAnimator = null;
        }
        if (binding != null) {
            binding.liveDot.setAlpha(1f);
        }
    }

    // ---------------------------------------------------------------------
    // Camera
    // ---------------------------------------------------------------------

    private boolean hasCameraPermission() {
        return ContextCompat.checkSelfPermission(this, Manifest.permission.CAMERA)
                == PackageManager.PERMISSION_GRANTED;
    }

    private void requestCameraPermission() {
        permissionRequested = true;
        permissionRequestInFlight = true;
        permissionLauncher.launch(Manifest.permission.CAMERA);
    }

    private boolean isPermissionPermanentlyDenied() {
        return permissionRequested
                && !shouldShowRequestPermissionRationale(Manifest.permission.CAMERA);
    }

    private void showPermissionPanel() {
        if (binding == null || isFinishing() || isDestroyed()) return;
        boolean permanent = isPermissionPermanentlyDenied();
        binding.tvPermissionMessage.setText(permanent
                ? R.string.live_permission_message_settings
                : R.string.live_permission_message);
        binding.btnGrantCamera.setText(permanent
                ? R.string.live_permission_settings
                : R.string.live_permission_allow);
        binding.permissionPanel.setVisibility(View.VISIBLE);
    }

    private void openAppSettings() {
        Intent intent = new Intent(Settings.ACTION_APPLICATION_DETAILS_SETTINGS,
                Uri.fromParts("package", getPackageName(), null));
        intent.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK);
        try {
            startActivity(intent);
        } catch (Exception ignored) {
            // No Settings app on the device: keep the panel and its retry button.
        }
    }

    private void ensureCamera() {
        if (cameraBound || cameraRequestInFlight || isFinishing() || isDestroyed()) return;
        if (!hasCameraPermission()) return;

        cameraRequestInFlight = true;
        final ListenableFuture<ProcessCameraProvider> future =
                ProcessCameraProvider.getInstance(this);
        future.addListener(() -> {
            cameraRequestInFlight = false;
            if (isFinishing() || isDestroyed()) return;
            ProcessCameraProvider provider;
            try {
                provider = future.get();
            } catch (Exception e) {
                showCameraError();
                return;
            }
            cameraProvider = provider;
            bindPreview(provider);
        }, ContextCompat.getMainExecutor(this));
    }

    private void bindPreview(@NonNull ProcessCameraProvider provider) {
        CameraSelector selector = CameraSelector.DEFAULT_FRONT_CAMERA;
        try {
            if (!provider.hasCamera(selector)) {
                selector = CameraSelector.DEFAULT_BACK_CAMERA;
            }
        } catch (CameraInfoUnavailableException e) {
            selector = CameraSelector.DEFAULT_BACK_CAMERA;
        }

        Preview preview = new Preview.Builder().build();
        preview.setSurfaceProvider(binding.previewView.getSurfaceProvider());

        // Safe here: this activity is the only camera owner in the process.
        provider.unbindAll();
        try {
            provider.bindToLifecycle(this, selector, preview);
            cameraBound = true;
            hideCameraError();
            binding.cameraBackdrop.setVisibility(View.GONE);
        } catch (Exception e) {
            cameraBound = false;
            showCameraError();
        }
    }

    private void releaseCamera() {
        cameraBound = false;
        cameraRequestInFlight = false;
        if (cameraProvider != null) {
            try {
                cameraProvider.unbindAll();
            } catch (Exception ignored) {
                // Provider already shut down.
            }
            cameraProvider = null;
        }
    }

    private void showCameraError() {
        if (binding == null) return;
        binding.btnCameraError.setVisibility(View.VISIBLE);
    }

    private void hideCameraError() {
        if (binding == null) return;
        binding.btnCameraError.setVisibility(View.GONE);
    }

    // ---------------------------------------------------------------------
    // Insets
    // ---------------------------------------------------------------------

    /**
     * Edge-to-edge: the preview fills the window while the chrome is padded by
     * the bars. IME insets are handled here because decorFitsSystemWindows is
     * off, so the topic field never ends up under the keyboard.
     */
    private void applyWindowInsets() {
        final int setupTopBarTop = binding.setupTopBar.getPaddingTop();
        final int setupBottomBottom = binding.setupBottom.getPaddingBottom();
        final int streamTopBarTop = binding.streamTopBar.getPaddingTop();
        final int streamBottomBottom = binding.streamBottom.getPaddingBottom();
        final ViewGroup.MarginLayoutParams errorParams =
                (ViewGroup.MarginLayoutParams) binding.btnCameraError.getLayoutParams();
        final int errorTopMargin = errorParams.topMargin;

        ViewCompat.setOnApplyWindowInsetsListener(binding.getRoot(), (v, insets) -> {
            Insets bars = insets.getInsets(WindowInsetsCompat.Type.systemBars());
            Insets ime = insets.getInsets(WindowInsetsCompat.Type.ime());
            int bottom = Math.max(bars.bottom, ime.bottom);

            binding.setupTopBar.setPadding(
                    binding.setupTopBar.getPaddingLeft(), setupTopBarTop + bars.top,
                    binding.setupTopBar.getPaddingRight(), binding.setupTopBar.getPaddingBottom());
            binding.setupBottom.setPadding(
                    binding.setupBottom.getPaddingLeft(), binding.setupBottom.getPaddingTop(),
                    binding.setupBottom.getPaddingRight(), setupBottomBottom + bottom);
            binding.streamTopBar.setPadding(
                    binding.streamTopBar.getPaddingLeft(), streamTopBarTop + bars.top,
                    binding.streamTopBar.getPaddingRight(), binding.streamTopBar.getPaddingBottom());
            binding.streamBottom.setPadding(
                    binding.streamBottom.getPaddingLeft(), binding.streamBottom.getPaddingTop(),
                    binding.streamBottom.getPaddingRight(), streamBottomBottom + bottom);

            // Sit just under the top bar in both states.
            errorParams.topMargin = errorTopMargin + bars.top + dp(56);
            binding.btnCameraError.setLayoutParams(errorParams);
            return insets;
        });
        ViewCompat.requestApplyInsets(binding.getRoot());
    }

    private int dp(int value) {
        return Math.round(value * getResources().getDisplayMetrics().density);
    }

    /** Immutable record of a rendered comment, used to rebuild the list. */
    private static final class Comment {
        final String username;
        final String message;

        Comment(String username, String message) {
            this.username = username;
            this.message = message;
        }
    }
